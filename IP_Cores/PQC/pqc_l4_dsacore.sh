# interoperate with itself perfectly, and not be ML-DSA. That is the
# RTL-vs-RTL common mode the Phase 0 test closed in the SpaceWire and 1553
# cores.
#
# The chain carries the core's own output: the driver moves the bytes KeyGen
# produced into the addresses Sign reads, not a reloaded vector.
#
# Adds new files only; nothing from Layer 3B is modified, and the six
# operation signatures are unchanged.
# Installs into: $HOME/vhdl_repo/IP_Cores/PQC/
