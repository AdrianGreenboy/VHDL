-------------------------------------------------------------------------------
-- SERDES_256G - TX lane (tx_clk domain): scrambler, alignment marker + BIP-8
-- insertion and 132 -> 128 bit gearbox towards the GT (raw mode, 128-bit).
--
-- Stage 1  self-synchronous scrambler x^58 + x^39 + 1 over the two 64-bit
--          payloads of the lane word (128 bits per clock, LSB first, block 0
--          then block 1). Sync headers bypass the scrambler. The scrambler
--          does not advance on alignment-marker slots.
-- Stage 2  alignment marker insertion (AM_A & AM_B, unscrambled) and BIP-8
--          accumulation over every non-marker word sent since the last
--          marker; the BIP is carried by the next AM_A.
-- Stage 3  gearbox: 32 words of 132 bits leave as 33 words of 128 bits. The
--          clock without input word (in_valid = '0', one in 33, generated by
--          serdes256g_tx_frame) flushes the 128 accumulated bits.
--
-- gt_txdata(0) is the first bit on the wire (GT sends LSB first).
--
-- MIT License.
-------------------------------------------------------------------------------
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use work.serdes256g_pkg.all;

entity serdes256g_tx_lane is
  generic (
    G_LANE_ID : natural := 0
  );
  port (
    clk       : in  std_logic;
    rst       : in  std_logic;
    in_word   : in  std_logic_vector(131 downto 0);
    in_valid  : in  std_logic;
    in_am     : in  std_logic;
    status    : in  std_logic_vector(7 downto 0);   -- carried by AM_B
    gt_txdata : out std_logic_vector(127 downto 0)
  );
end entity serdes256g_tx_lane;

architecture rtl of serdes256g_tx_lane is
  signal scr_state : unsigned(57 downto 0) := (others => '1');
  signal s1_word   : std_logic_vector(131 downto 0) := (others => '0');
  signal s1_valid  : std_logic := '0';
  signal s1_am     : std_logic := '0';

  signal bip       : std_logic_vector(7 downto 0) := (others => '0');
  signal s2_word   : std_logic_vector(131 downto 0) := (others => '0');
  signal s2_valid  : std_logic := '0';

  signal gb_cnt    : unsigned(5 downto 0) := (others => '0');
  signal gb_rem    : unsigned(131 downto 0) := (others => '0');
  signal gt_r      : std_logic_vector(127 downto 0) := (others => '0');
begin

  process(clk)
    variable s   : unsigned(57 downto 0);
    variable pin : std_logic_vector(127 downto 0);
    variable po  : std_logic_vector(127 downto 0);
    variable sb  : std_logic;
    variable w   : std_logic_vector(131 downto 0);
    variable v   : unsigned(259 downto 0);
    variable sd  : unsigned(57 downto 0);
  begin
    if rising_edge(clk) then
      if rst = '1' then
        -- per-lane seed so that idle lanes are not bit-identical
        sd := (others => '1');
        sd(11 downto 8) := to_unsigned(G_LANE_ID mod 16, 4);
        scr_state <= sd;
        s1_word   <= (others => '0');
        s1_valid  <= '0';
        s1_am     <= '0';
        bip       <= (others => '0');
        s2_word   <= (others => '0');
        s2_valid  <= '0';
        gb_cnt    <= (others => '0');
        gb_rem    <= (others => '0');
        gt_r      <= (others => '0');
      else
        ---------------------------------------------------------------------
        -- stage 1: scrambler
        ---------------------------------------------------------------------
        s1_valid <= in_valid;
        s1_am    <= in_am;
        if in_valid = '1' and in_am = '0' then
          pin := in_word(131 downto 68) & in_word(65 downto 2);
          s   := scr_state;
          for i in 0 to 127 loop
            sb    := pin(i) xor s(38) xor s(57);
            po(i) := sb;
            s     := s(56 downto 0) & sb;
          end loop;
          scr_state <= s;
          s1_word   <= po(127 downto 64) & in_word(67 downto 66)
                     & po(63 downto 0)   & in_word(1 downto 0);
        end if;

        ---------------------------------------------------------------------
        -- stage 2: alignment marker + BIP-8
        ---------------------------------------------------------------------
        s2_valid <= s1_valid;
        if s1_valid = '1' then
          if s1_am = '1' then
            w   := f_am_b(status) & f_am_a(G_LANE_ID, bip);
            bip <= (others => '0');
          else
            w   := s1_word;
            bip <= bip xor f_bip8(s1_word);
          end if;
          s2_word <= w;
        end if;

        ---------------------------------------------------------------------
        -- stage 3: gearbox 132 -> 128
        ---------------------------------------------------------------------
        if s2_valid = '1' then
          v := shift_left(resize(unsigned(s2_word), 260),
                          4*to_integer(gb_cnt(4 downto 0)));
          v(131 downto 0) := v(131 downto 0) or gb_rem;
          gt_r   <= std_logic_vector(v(127 downto 0));
          gb_rem <= v(259 downto 128);
          gb_cnt <= gb_cnt + 1;
        else
          gt_r   <= std_logic_vector(gb_rem(127 downto 0));
          gb_rem <= (others => '0');
          gb_cnt <= (others => '0');
        end if;
      end if;
    end if;
  end process;

  gt_txdata <= gt_r;

end architecture rtl;
