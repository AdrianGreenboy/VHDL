-- eth_mac.vhd - MAC Ethernet 10/100 completo (familia TSN v1 / PTP)
-- ---------------------------------------------------------------------------
-- TX MII engine + RX MII engine + clock-enable generation + LOOP_INT mux.
-- Shared by ETH, PTP (byte-identical copy) and indirectly TSN.
--
--   loopback='1' (LOOP_INT): the TX nibbles are fed back to the RX engine
--                inside the core. Both engines run on the internal /4 clock
--                enable (25 MHz nibble rate from the 100 MHz core). No PHY
--                clock is involved. Unchanged from v1 (bit-exact timing).
--   loopback='0' (external PHY, audit 2026-11 ALTA fix): real MII.
--                mii_rx_clk / mii_tx_clk are PHY-driven clocks; eth_mii_cdc
--                samples RXD/RX_DV on RX_CLK, launches TXD/TX_EN on TX_CLK and
--                moves the nibble streams through Gray-pointer async FIFOs.
--                The engines (core domain) are paced by the CDC enables.
--                tx_sfd_pulse is the wire instant of the TX SFD (pulse-
--                synchronized from TX_CLK); rx_sfd_pulse is generated by the RX
--                engine after the RX FIFO (fixed latency, +/-1 core clock).
--                Switch 'loopback' only while the port is idle.
--
-- Requirements: f_clk >= 2 x f_mii (100 MHz core vs 25 MHz MII: 4x).
-- Reset: rst is synchronous active-high in the core domain; the PHY domains
-- get their own reset synchronizers inside eth_mii_cdc.
-- ---------------------------------------------------------------------------
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity eth_mac is
  generic (
    G_MAXLEN : integer := 1518                     -- max frame incl. FCS
  );
  port (
    clk       : in  std_logic;                     -- 100 MHz del core
    rst       : in  std_logic;                      -- sincrono activo-alto
    loopback  : in  std_logic;                      -- '1' LOOP_INT, '0' PHY ext
    -- configuracion RX
    macaddr   : in  std_logic_vector(47 downto 0);
    promisc   : in  std_logic;
    -- flujo TX (bytes de trama)
    tx_data   : in  std_logic_vector(7 downto 0);
    tx_valid  : in  std_logic;
    tx_last   : in  std_logic;
    tx_ready  : out std_logic;
    tx_busy   : out std_logic;
    tx_underrun : out std_logic;
    -- flujo RX (bytes de trama aceptada)
    rx_data   : out std_logic_vector(7 downto 0);
    rx_valid  : out std_logic;
    rx_last   : out std_logic;
    rx_ev_ok  : out std_logic;
    rx_ev_crc : out std_logic;
    rx_ev_runt: out std_logic;
    rx_ev_drop: out std_logic;
    rx_ev_oversize : out std_logic;                 -- frame > G_MAXLEN dropped
    rx_dbg_dst: out std_logic_vector(47 downto 0);
    rx_dbg_nb : out std_logic_vector(11 downto 0);
    -- CDC diagnostics (pulses, external PHY mode only)
    phy_rx_ovf : out std_logic;                     -- RX nibble FIFO overflow
    phy_tx_unf : out std_logic;                     -- TX nibble FIFO starved mid-frame
    -- pines MII (PHY externo)
    mii_rx_clk : in  std_logic := '0';              -- PHY RX_CLK (25/2.5 MHz)
    mii_tx_clk : in  std_logic := '0';              -- PHY TX_CLK (25/2.5 MHz)
    mii_txd   : out std_logic_vector(3 downto 0);
    mii_tx_en : out std_logic;
    mii_rxd   : in  std_logic_vector(3 downto 0);
    mii_rx_dv : in  std_logic;
    -- ganchos PTP:
    tx_sfd_pulse : out std_logic;                   -- SFD emitido (para TS TX)
    rx_sfd_pulse : out std_logic;                   -- SFD detectado (para TS RX)
    -- override 1-step del TX (parcheo de originTimestamp/correctionField)
    ovr_en    : in  std_logic := '0';
    ovr_off   : in  std_logic_vector(10 downto 0) := (others => '0');
    ovr_len   : in  std_logic_vector(3 downto 0)  := (others => '0');
    ovr_data  : in  std_logic_vector(79 downto 0) := (others => '0')
  );
end entity eth_mac;

architecture rtl of eth_mac is

  signal int_ce  : std_logic := '0';
  signal cediv   : unsigned(1 downto 0) := (others => '0');

  -- clock-enables actually applied to the engines
  signal tx_ce, rx_ce : std_logic;

  -- lineas internas del TX
  signal txd_i   : std_logic_vector(3 downto 0);
  signal txen_i  : std_logic;
  signal tx_sfd_eng : std_logic;
  -- lineas que entran al RX (tras el mux LOOP_INT)
  signal rxd_i   : std_logic_vector(3 downto 0);
  signal rxdv_i  : std_logic;

  -- external-PHY CDC
  signal x_rx_ce, x_rx_dv, x_tx_ce, x_sfd_wire : std_logic;
  signal x_rx_nib : std_logic_vector(3 downto 0);
  signal x_ovf, x_unf : std_logic;
  signal pad_txd : std_logic_vector(3 downto 0);
  signal pad_txen : std_logic;
  signal cdc_txen, cdc_sfd : std_logic;

begin

  -- generador de mii_ce interno: pulso 1 de cada 4 ciclos (25 MHz)
  process(clk)
  begin
    if rising_edge(clk) then
      if rst = '1' then
        cediv  <= (others => '0');
        int_ce <= '0';
      elsif cediv = 3 then
        cediv  <= (others => '0');
        int_ce <= '1';
      else
        cediv  <= cediv + 1;
        int_ce <= '0';
      end if;
    end if;
  end process;

  -- external PHY interface (always instantiated; idle in LOOP_INT)
  u_cdc : entity work.eth_mii_cdc
    port map (
      clk => clk, rst => rst,
      rx_ce => x_rx_ce, rx_nib => x_rx_nib, rx_dv => x_rx_dv,
      tx_ce => x_tx_ce, tx_nib => txd_i, tx_en => cdc_txen, tx_sfd => cdc_sfd,
      tx_sfd_wire => x_sfd_wire, rx_ovf => x_ovf, tx_unf => x_unf,
      mii_rx_clk => mii_rx_clk, mii_rxd => mii_rxd, mii_rx_dv => mii_rx_dv,
      mii_tx_clk => mii_tx_clk, mii_txd => pad_txd, mii_tx_en => pad_txen);

  -- mux LOOP_INT (all core-domain signals: no clock mux)
  tx_ce  <= int_ce when loopback = '1' else x_tx_ce;
  rx_ce  <= int_ce when loopback = '1' else x_rx_ce;
  rxd_i  <= txd_i  when loopback = '1' else x_rx_nib;
  rxdv_i <= txen_i when loopback = '1' else x_rx_dv;
  tx_sfd_pulse <= tx_sfd_eng when loopback = '1' else x_sfd_wire;
  phy_rx_ovf <= x_ovf and not loopback;
  phy_tx_unf <= x_unf and not loopback;

  -- pads: external PHY -> TX_CLK pad registers of eth_mii_cdc. LOOP_INT ->
  -- the engine lines, as in v1 (the pads mirror the looped traffic for
  -- observability; inert downstream). 'loopback' is a static mode select, so
  -- this output mux never switches while a PHY samples the pins. In LOOP_INT
  -- the CDC is fed TX_EN=0 so its FIFO only carries idle nibbles.
  cdc_txen  <= txen_i and not loopback;
  cdc_sfd   <= tx_sfd_eng and not loopback;
  mii_txd   <= txd_i  when loopback = '1' else pad_txd;
  mii_tx_en <= txen_i when loopback = '1' else pad_txen;

  u_tx : entity work.eth_tx_mii
    port map (
      clk => clk, rst => rst, mii_ce => tx_ce,
      tx_data => tx_data, tx_valid => tx_valid, tx_last => tx_last,
      tx_ready => tx_ready, tx_busy => tx_busy, underrun => tx_underrun,
      txd => txd_i, tx_en => txen_i, tx_sfd_pulse => tx_sfd_eng,
      ovr_en => ovr_en, ovr_off => ovr_off, ovr_len => ovr_len, ovr_data => ovr_data);

  u_rx : entity work.eth_rx_mii
    generic map (G_MAXLEN => G_MAXLEN)
    port map (
      clk => clk, rst => rst, mii_ce => rx_ce,
      macaddr => macaddr, promisc => promisc,
      rxd => rxd_i, rx_dv => rxdv_i,
      rx_data => rx_data, rx_valid => rx_valid, rx_last => rx_last,
      ev_ok => rx_ev_ok, ev_crc => rx_ev_crc, ev_runt => rx_ev_runt, ev_drop => rx_ev_drop,
      ev_oversize => rx_ev_oversize,
      dbg_dst => rx_dbg_dst, dbg_nb => rx_dbg_nb,
      rx_sfd_pulse => rx_sfd_pulse);

end architecture rtl;
