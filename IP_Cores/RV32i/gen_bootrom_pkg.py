#!/usr/bin/env python3
# =============================================================================
#  gen_bootrom_pkg.py  -  .mem (hex, one 32-bit word per line) -> VHDL package
#  with the boot ROM constant used by boot_loader.vhd.
#
#  Usage:  python3 gen_bootrom_pkg.py <program.mem> [rv32_bootrom_pkg.vhd]
#
#  The ROM is a plain VHDL constant: no textio, synthesizable for ASIC
#  (becomes ROM / logic) and FPGA alike.
# =============================================================================
import sys, re

def main():
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else "rv32_bootrom_pkg.vhd"
    words = []
    for line in open(src):
        t = line.strip()
        if not t:
            continue
        if not re.fullmatch(r"[0-9a-fA-F]{1,8}", t):
            sys.exit(f"{src}: bad line '{t}'")
        words.append(int(t, 16))
    if not words:
        sys.exit(f"{src}: empty program")
    body = ",\n".join(f'    {i} => x"{w:08X}"' for i, w in enumerate(words))
    with open(dst, "w") as f:
        f.write(f"""-- =============================================================================
--  rv32_bootrom_pkg.vhd  -  Boot ROM contents for boot_loader.vhd
--  GENERATED by gen_bootrom_pkg.py from {src.split('/')[-1]} - do not edit.
--  {len(words)} words.
-- =============================================================================
library ieee;
use ieee.std_logic_1164.all;

package rv32_bootrom_pkg is
  type boot_rom_t is array (natural range <>) of std_logic_vector(31 downto 0);
  constant BOOT_ROM : boot_rom_t(0 to {len(words) - 1}) := (
{body}
  );
end package rv32_bootrom_pkg;
""")
    print(f"{dst}: {len(words)} words from {src}")

if __name__ == "__main__":
    main()
