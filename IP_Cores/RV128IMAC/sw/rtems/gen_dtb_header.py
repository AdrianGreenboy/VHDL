#!/usr/bin/env python3
"""gen_dtb_header.py - DTS -> DTB (dtc) -> C header with system_dtb[] for the RTEMS riscv
BSP option BSP_DTB_HEADER_PATH (same layout as the headers rtems-bin2c makes).
Usage: gen_dtb_header.py <file.dts> <out.h>"""
import os, subprocess, sys, tempfile
dts, out = sys.argv[1], sys.argv[2]
with tempfile.TemporaryDirectory() as d:
    dtb = os.path.join(d, 'system.dtb')
    subprocess.run(['dtc', '-I', 'dts', '-O', 'dtb', '-o', dtb, dts], check=True)
    data = open(dtb, 'rb').read()
lines = [', '.join(f'0x{b:02x}' for b in data[i:i + 12]) for i in range(0, len(data), 12)]
with open(out, 'w') as f:
    f.write('/* GENERATED by sw/rtems/gen_dtb_header.py from %s - do not edit */\n' % os.path.basename(dts))
    f.write('#include <stddef.h>\n#include <rtems/score/basedefs.h>\n\n')
    f.write('const unsigned char system_dtb[] RTEMS_ALIGNED(8) = {\n  ')
    f.write(',\n  '.join(lines))
    f.write('\n};\n\nconst size_t system_dtb_size = sizeof(system_dtb);\n')
print(f'{out}: {len(data)} bytes of DTB')
