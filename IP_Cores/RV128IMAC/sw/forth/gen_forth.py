def rotr64(dst, src, n, tmp):
    """64-bit rotate right: Zbb rorid (one instruction, result sign-extended from bit 63)"""
    return [f"  rorid {dst}, {src}, {n}"]


def low64(r):
    return [f"  slli {r}, {r}, 64", f"  srli {r}, {r}, 64"]


