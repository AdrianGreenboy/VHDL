        "  srai t2, t1, 127", "  xor t1, t1, t2", "  sub t1, t1, t2",
        "  divu t3, t0, t1", "  remu t4, t0, t1",
        # fast path |b| < 2^96: the fraction in two 32-bit steps of the 128-bit divider
        "  srli a2, t1, 96", "  bnez a2, fq_slow",
        "  slli t4, t4, 32", "  divu a3, t4, t1", "  remu t4, t4, t1",
        "  slli t4, t4, 32", "  divu a4, t4, t1", "  slli a3, a3, 32", "  or t5, a3, a4", "  j fq_done",
